/**
 * Les écritures du déroulé du module 1, telles que les panneaux les affichent.
 *
 * `ECRITURES[chapitre][panneau][ligne]` — le chapitre 0 est l'avant-propos, il ne porte jamais
 * d'écriture.
 *
 * Ce sont des données de référence, figées : rien ne les écrit, ni ici ni dans les composants. Elles
 * ont longtemps vécu dans le store du module, où un `shallowRef` immuable ne faisait que laisser
 * croire à une mécanique.
 *
 * Sur l'emplacement — `app/utils/m1/` et pas le premier niveau de `utils/` — voir l'en-tête de
 * `comptes.ts` : ce sous-dossier échappe à l'auto-import, donc au registre global.
 */

export type SensCol = 'débit' | 'crédit'

export interface GdJalLigne {
  cpt: string
  libelle: string
  somme: number
  col: SensCol
}

// CL — une écriture comptable d'un panneau ; « todo » = manuelle, « auto » = déjà comptabilisée
export interface EcritureCompta {
  id: string
  doc: string
  action: string
  somme: number
  info: string
  type: 'todo' | 'auto'
  gdJal: GdJalLigne | null
  /** La ligne se saisit au grand journal : son compte n'a pas de case (4456, 4457). */
  gdJalTodo?: true
  /**
   * CL — L'inverse de `gdJalTodo` : la ligne a une case mais ne passe pas par le journal. Une seule
   * dans le module (le résultat au Bilan, Chapitre 11), et c'est justement pour cette raison que
   * l'information est déclarée plutôt que devinée : `gdJal` porte ailleurs le compte et la colonne,
   * et sans lui il ne resterait que `doc` et `info`, deux chaînes écrites pour être lues à l'écran.
   * Faire dépendre une saisie de leur analyse, c'est casser la grille en corrigeant une formulation.
   */
  grilleSeule?: { cpt: string, col: SensCol }
}

